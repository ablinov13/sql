-- 3. Запросы SELECT

-- Запрос 1: детективы дешевле 450 рублей
SELECT title, price FROM books WHERE genre = 'Детектив' AND price < 450;

-- Запрос 2: пять самых дорогих книг
SELECT title, genre, price FROM books ORDER BY price DESC LIMIT 5;

-- Запрос 3: количество книг и средняя цена по каждому жанру
SELECT genre, COUNT(*) AS books_count, CAST(ROUND(AVG(price)) AS INTEGER) AS avg_price
FROM books
GROUP BY genre
ORDER BY books_count DESC, genre;
