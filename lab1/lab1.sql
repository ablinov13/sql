-- 1. Создание таблицы
DROP TABLE IF EXISTS books;
CREATE TABLE books (
    title    TEXT    NOT NULL,  -- название книги
    genre    TEXT    NOT NULL,  -- жанр (категория)
    price    INTEGER NOT NULL,  -- цена в рублях
    year     INTEGER NOT NULL,  -- год издания
    author   TEXT    NOT NULL   -- автор
);

